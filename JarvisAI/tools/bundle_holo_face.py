"""Bundle the hologram into one self-contained HTML file.

Why this exists
---------------
The served page lives at ``assets/holo/face/`` and needs *something* to serve it
(the Qt HUD, a static server, or the Arena preview proxy). That is fine for
integration, but it makes the page awkward to look at on its own — a plain
``file://`` open works, yet the folder has to travel intact.

This script fuses everything into a single ``hologram-standalone.html``:

* ``style.css``      -> ``<style>``
* ``face_data.js``   -> ``<script>``
* ``hologram.js``    -> ``<script>``
* every image        -> ``data:`` URI

The result opens by double-click, from a USB stick, or as an email attachment,
with no server, no network access and no build step. It is a *build artefact*
for reviewing the hologram; the real integration point stays the folder itself.

Usage::

    python JarvisAI/tools/bundle_holo_face.py \
        --source JarvisAI/assets/holo/face \
        --out    JarvisAI/assets/holo/face/hologram-standalone.html
"""
from __future__ import annotations

import argparse
import base64
import mimetypes
import re
from pathlib import Path


def data_uri(path: Path) -> str:
    mime = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
    payload = base64.b64encode(path.read_bytes()).decode("ascii")
    return f"data:{mime};base64,{payload}"


def build(source: Path, out: Path) -> None:
    html = (source / "index.html").read_text(encoding="utf-8")
    css = (source / "style.css").read_text(encoding="utf-8")
    face_js = (source / "face_data.js").read_text(encoding="utf-8")
    holo_js = (source / "hologram.js").read_text(encoding="utf-8")

    # <link rel="stylesheet" href="style.css"> -> inline
    html = re.sub(
        r'<link rel="stylesheet" href="style\.css">',
        lambda _m: f"<style>\n{css}\n</style>",
        html,
    )

    # <script src="face_data.js"></script> / hologram.js -> inline
    html = html.replace(
        '<script src="face_data.js"></script>',
        f"<script>\n{face_js}\n</script>",
    )
    html = html.replace(
        '<script src="hologram.js"></script>',
        f"<script>\n{holo_js}\n</script>",
    )

    # every local src="…" -> data URI
    def inline_src(match: re.Match[str]) -> str:
        attr, rel = match.group(1), match.group(2)
        if rel.startswith(("data:", "http:", "https:", "#")):
            return match.group(0)
        target = (source / rel).resolve()
        if not target.is_file():
            raise SystemExit(f"missing asset referenced by the page: {rel}")
        return f'{attr}="{data_uri(target)}"'

    html = re.sub(r'(\bsrc)="([^"]+)"', inline_src, html)

    leftover = [
        m for m in re.findall(r'(?:src|href)="([^"]+)"', html)
        if not m.startswith("data:")
    ]
    if leftover:
        raise SystemExit(f"still referencing external files: {leftover}")

    header = (
        "<!-- Single-file build of the BIHANSA hologram.\n"
        "     Generated by JarvisAI/tools/bundle_holo_face.py — do not edit.\n"
        "     Opens directly from disk; no server, no network. -->\n"
    )
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(header + html, encoding="utf-8")
    size_mb = out.stat().st_size / (1024 * 1024)
    print(f"wrote {out} ({size_mb:.2f} MB)")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--source", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    build(args.source, args.out)


if __name__ == "__main__":
    main()
