// Resolves the hologram's GLSL sources into one TypeScript module (P4).
//   src/hologram/shaders/*.glsl      material shaders (one file per vertex/fragment stage)
//   src/hologram/shaders/lib/*.glsl  function library (the old chunks), composed by chunks.ts
// `#include "lygia/…"` pulls functions from LYGIA (node_modules/lygia) and `#include "./x.glsl"` a local file;
// each file is inlined once per output (LYGIA's own #ifndef guards make repeats harmless too).
// Output: src/hologram/shaders/glsl.generated.ts. Run: npm run shaders. CI fails when it is stale.
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SHADERS = join(root, 'src', 'hologram', 'shaders');
const LYGIA = join(root, 'node_modules', 'lygia');
const INCLUDE = /^[ \t]*#include\s+"([^"]+)"[ \t]*$/gm;

function resolveIncludes(file, seen = new Set()) {
    const src = readFileSync(file, 'utf8');
    return src.replace(INCLUDE, (_, spec) => {
        const target = spec.startsWith('lygia/') ? join(LYGIA, spec.slice('lygia/'.length)) : resolve(dirname(file), spec);
        if (!existsSync(target)) throw new Error(`${relative(root, file)}: cannot find #include "${spec}"`);
        if (seen.has(target)) return `// (already included: ${spec})`;
        seen.add(target);
        const label = spec.startsWith('lygia/') ? `${spec} (LYGIA, Prosperity/Patron licence)` : spec;
        return `// ── ${label}\n${resolveIncludes(target, seen).trim()}`;
    });
}

const entries = [];
for (const dir of [SHADERS, join(SHADERS, 'lib')]) {
    for (const name of readdirSync(dir).filter((n) => n.endsWith('.glsl')).sort()) {
        const key = relative(SHADERS, join(dir, name)).replace(/\\/g, '/').replace(/\.glsl$/, '');
        entries.push([key, resolveIncludes(join(dir, name)).trim() + '\n']);
    }
}
const ts =
    `// Generated by frontend/scripts/build-shaders.mjs from src/hologram/shaders/**/*.glsl. Do not edit.\n` +
    `export const GLSL = {\n` +
    entries.map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n') +
    `\n} as const;\nexport type ShaderName = keyof typeof GLSL;\n`;
writeFileSync(join(SHADERS, 'glsl.generated.ts'), ts);
console.log(`shaders: ${entries.length} sources -> glsl.generated.ts`);
