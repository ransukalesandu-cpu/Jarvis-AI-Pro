SPACING = {"xxs": 2, "xs": 4, "sm": 8, "md": 12, "lg": 16, "xl": 24, "xxl": 32}
RADII = {"sm": 6, "md": 10, "lg": 16, "pill": 999}
TYPE = {
    "mono": "JetBrains Mono, Cascadia Mono, Consolas, monospace",
    "sans": "Segoe UI, Inter, Roboto, sans-serif",
    "xs": 10, "sm": 11, "md": 13, "lg": 16, "xl": 20, "xxl": 28,
}
MOTION = {                     # milliseconds
    "instant": 60, "fast": 120, "base": 220, "slow": 400, "drift": 1200,
    "easing": "cubic-bezier(0.2, 0.8, 0.2, 1)",
}
Z = {"stage": 0, "dock": 10, "window": 20, "menu": 30, "bar": 35, "palette": 40,
     "island": 50, "toast": 60}

# Assistant states the HUD can show, and the colour role each one uses.
STATE_ROLES = {
    "idle": "primary", "listening": "ok", "thinking": "accent2", "speaking": "accent",
    "sleeping": "text_dim", "error": "danger", "offline": "text_dim",
}


def _hex(rgb) -> str:
    return "#{:02x}{:02x}{:02x}".format(*rgb)


def tokens(persona: str = "jarvis") -> dict:
    """Every token for one persona, as nested plain data."""
    pal = PALETTES.get(persona, PALETTES["jarvis"])
    holo = {k: _hex(v) for k, v in pal.as_dict().items() if k != "mode"}
    return {
        "persona": pal.mode,
        "color": dict(BASE_COLORS),
        "holo": holo,
        "glass": dict(GLASS),
        "space": dict(SPACING),
        "radius": dict(RADII),
        "type": dict(TYPE),
        "motion": dict(MOTION),
        "z": dict(Z),
        "state": {s: BASE_COLORS[role] for s, role in STATE_ROLES.items()},
    }


def state_color(state: str) -> str:
    """The chrome colour for an assistant state (unknown states read as idle)."""
    return BASE_COLORS[STATE_ROLES.get(str(state).lower(), "primary")]


def to_json(tok: dict) -> str:
    return json.dumps(tok, indent=2, sort_keys=True) + "\n"


def to_css(tok: dict) -> str:
    """CSS custom properties: --jv-<group>-<name>."""
    lines = ["/* Generated by core/ui_tokens.py - edit the tokens there, not here. */", ":root {"]
    for group in ("color", "holo", "glass", "space", "radius", "type", "motion", "z", "state"):
        for name, value in sorted(tok[group].items()):
            if isinstance(value, (int, float)) and group in ("space", "radius") or (
                    group == "type" and isinstance(value, int)):
                value = f"{value}px"
            elif group == "motion" and isinstance(value, int):
                value = f"{value}ms"
            lines.append(f"  --jv-{group}-{name.replace('_', '-')}: {value};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def export(directory: Path = ASSETS, persona: str = "jarvis") -> list[Path]:
    """Write theme.json and theme.css; returns the paths written.

    Not "tokens.json": the repository ignores *token*.json so secrets never
    get committed by accident.
    """
    tok = tokens(persona)
    directory.mkdir(parents=True, exist_ok=True)
    out = [directory / "theme.json", directory / "theme.css"]
    out[0].write_text(to_json(tok), encoding="utf-8")
    out[1].write_text(to_css(tok), encoding="utf-8")
    return out


if __name__ == "__main__":       # python -m core.ui_tokens
    for path in export():
        print(f"wrote {path}")
