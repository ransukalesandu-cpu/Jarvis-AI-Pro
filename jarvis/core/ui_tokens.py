"""Design tokens: the one theme every surface of the HUD draws from.

Colours, glass, spacing, radii, type, motion timings and z-order live here as
plain data. Qt widgets read them through ``ui.C`` (which takes its defaults
from :data:`BASE_COLORS`), painted renderers through :func:`tokens`, and the
web pieces (smart panel, hub client) through the exported
``ui/assets/theme.json`` / ``theme.css``. Change a value here and every one
of them follows; ``python -m core.ui_tokens`` rewrites the exported files and
a test fails if they drift.

Pure data and arithmetic: no Qt, no I/O except :func:`export`.
"""
